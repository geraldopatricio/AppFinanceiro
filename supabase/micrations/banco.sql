/*
# Create Finance Manager schema

1. New Tables
- `customers`: clients managed by the business, including contact and status details.
- `suppliers`: vendors managed by the business, including contact and status details.
- `sales_orders`: sales orders that represent expected or received revenue.
- `purchase_orders`: purchase orders that represent expected or paid expenses.
- `financial_transactions`: manual entries and automatic financial movements linked to orders.

2. Data fields
- All tables use UUID primary keys and timestamps.
- Customer and supplier records store name, document, phone, email, notes, and active status.
- Orders store party name, description, amount, due date, status, and payment date.
- Transactions store type, description, amount, category, date, and optional order reference.

3. Security
- Row Level Security is enabled on every table.
- This is intentionally a single-device, no-sign-in app, so anon and authenticated roles receive CRUD access.

4. Important notes
- Order and transaction records are retained when related contacts are removed by using nullable references.
- Financial amounts use numeric(14,2) to preserve currency precision.
*/

CREATE TABLE IF NOT EXISTS CUSTOMERS (
    ID UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
    NAME TEXT NOT NULL,
    DOCUMENT TEXT,
    PHONE TEXT,
    EMAIL TEXT,
    NOTES TEXT,
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS SUPPLIERS (
    ID UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
    NAME TEXT NOT NULL,
    DOCUMENT TEXT,
    PHONE TEXT,
    EMAIL TEXT,
    NOTES TEXT,
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS SALES_ORDERS (
    ID UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
    CUSTOMER_ID UUID REFERENCES CUSTOMERS(ID) ON DELETE SET NULL,
    CUSTOMER_NAME TEXT NOT NULL,
    DESCRIPTION TEXT NOT NULL,
    AMOUNT NUMERIC(14, 2) NOT NULL CHECK (AMOUNT >= 0),
    DUE_DATE DATE,
    PAID_AT TIMESTAMPTZ,
    STATUS TEXT NOT NULL DEFAULT 'pending' CHECK (STATUS IN ('pending', 'received', 'cancelled')),
    CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS PURCHASE_ORDERS (
    ID UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
    SUPPLIER_ID UUID REFERENCES SUPPLIERS(ID) ON DELETE SET NULL,
    SUPPLIER_NAME TEXT NOT NULL,
    DESCRIPTION TEXT NOT NULL,
    AMOUNT NUMERIC(14, 2) NOT NULL CHECK (AMOUNT >= 0),
    DUE_DATE DATE,
    PAID_AT TIMESTAMPTZ,
    STATUS TEXT NOT NULL DEFAULT 'pending' CHECK (STATUS IN ('pending', 'paid', 'cancelled')),
    CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS FINANCIAL_TRANSACTIONS (
    ID UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
    TYPE TEXT NOT NULL CHECK (TYPE IN ('income', 'expense')),
    DESCRIPTION TEXT NOT NULL,
    AMOUNT NUMERIC(14, 2) NOT NULL CHECK (AMOUNT > 0),
    CATEGORY TEXT NOT NULL DEFAULT 'other',
    TRANSACTION_DATE DATE NOT NULL DEFAULT CURRENT_DATE,
    SALES_ORDER_ID UUID REFERENCES SALES_ORDERS(ID) ON DELETE SET NULL,
    PURCHASE_ORDER_ID UUID REFERENCES PURCHASE_ORDERS(ID) ON DELETE SET NULL,
    CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS SALES_ORDERS_CREATED_AT_IDX ON SALES_ORDERS(CREATED_AT DESC);

CREATE INDEX IF NOT EXISTS PURCHASE_ORDERS_CREATED_AT_IDX ON PURCHASE_ORDERS(CREATED_AT DESC);

CREATE INDEX IF NOT EXISTS FINANCIAL_TRANSACTIONS_DATE_IDX ON FINANCIAL_TRANSACTIONS(TRANSACTION_DATE DESC);

